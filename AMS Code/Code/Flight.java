    private void addFlightButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addFlightButtonActionPerformed
        String flightNumber = JOptionPane.showInputDialog(this, "Enter flight number:");
        String equipmentId = JOptionPane.showInputDialog(this, "Enter equipment ID:");
        String arrivalTime = JOptionPane.showInputDialog(this, "Enter arrival time:");
        String departureTime = JOptionPane.showInputDialog(this, "Enter departure time:");
        String airlineId = JOptionPane.showInputDialog(this, "Enter airline ID:");
        String gateId = JOptionPane.showInputDialog(this, "Enter gate ID:");
        try {
            PreparedStatement pst = conn.prepareStatement("INSERT INTO flight (Flight_Number, Equipment_ID, Arrival_time, Departure_time, Airline_ID, Gate_ID) VALUES (?, ?, ?, ?, ?, ?)");
            pst.setString(1, flightNumber);
            pst.setString(2, equipmentId);
            pst.setString(3, arrivalTime);
            pst.setString(4, departureTime);
            pst.setString(5, airlineId);
            pst.setString(6, gateId);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Flight added successfully!");
            displayFlights();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error adding flight: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_addFlightButtonActionPerformed

    private void updateFlightButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateFlightButtonActionPerformed
        int selectedRow = flightTable.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a flight to update!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int flightId = (int) flightTable.getValueAt(selectedRow, 0);
        String flightNumber = JOptionPane.showInputDialog(this, "Enter new flight number:");
        String equipmentId = JOptionPane.showInputDialog(this, "Enter new equipment ID:");
        String arrivalTime = JOptionPane.showInputDialog(this, "Enter new arrival time:");
        String departureTime = JOptionPane.showInputDialog(this, "Enter new departure time:");
        String airlineId = JOptionPane.showInputDialog(this, "Enter new airline ID:");
        String gateId = JOptionPane.showInputDialog(this, "Enter new gate ID:");
        try {
            PreparedStatement pst = conn.prepareStatement("UPDATE flight SET Flight_Number=?, Equipment_ID=?, Arrival_time=?, Departure_time=?, Airline_ID=?, Gate_ID=? WHERE Flight_ID=?");
            pst.setString(1, flightNumber);
            pst.setString(2, equipmentId);
            pst.setString(3, arrivalTime);
            pst.setString(4, departureTime);
            pst.setString(5, airlineId);
            pst.setString(6, gateId);
            pst.setInt(7, flightId);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Flight updated successfully!");
            displayFlights();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error updating flight: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_updateFlightButtonActionPerformed

    private void deleteFlightButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteFlightButtonActionPerformed
        int selectedRow = flightTable.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a flight to delete!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int flightId = (int) flightTable.getValueAt(selectedRow, 0);
        int confirmation = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this flight?", "Confirmation", JOptionPane.YES_NO_OPTION);
        if (confirmation == JOptionPane.YES_OPTION) {
            try {
                PreparedStatement pst = conn.prepareStatement("DELETE FROM flight WHERE Flight_ID=?");
                pst.setInt(1, flightId);
                pst.executeUpdate();
                JOptionPane.showMessageDialog(this, "Flight deleted successfully!");
                displayFlights();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Error deleting flight: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_deleteFlightButtonActionPerformed

    private void displayFlights() {
        try {
            PreparedStatement pst = conn.prepareStatement("SELECT * FROM flight");
            ResultSet rs = pst.executeQuery();
            DefaultTableModel model = (DefaultTableModel) flightTable.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                Object[] row = {
                    rs.getInt("Flight_ID"),
                    rs.getString("Flight_Number"),
                    rs.getString("Equipment_ID"),
                    rs.getString("Arrival_time"),
                    rs.getString("Departure_time"),
                    rs.getString("Airline_ID"),
                    rs.getString("Gate_ID")
                };
                model.addRow(row);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error fetching flights: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

